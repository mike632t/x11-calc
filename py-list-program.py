import sys, os

VERSION = "0.5.0031"

def _about():
  _path = os.path.basename(sys.argv[0])
  sys.stdout.write(
    "Usage: " + sys.argv[0] + "[OPTION]... [FILE]...\n"
    "Lists program steps from saved data FILE(s).\n" + "\n" +
    "  -a, --ansi               use ansi escape sequences (default)\n" +
    "  -h, --html               use html\n" +
    "  -m, --markup             use markup (for forum posts)\n" +
    "  -t, --text               use plain text\n" +
    "  -u, --unicode            display listing using unicode characters\n" +
    "      --all                list all program steps\n" +
    "      --model <model>      model name (25c, 33c 67 etc)\n" +
    "      --steps <nn>         number of steps to display\n" +
    "      --help               display this help and exit\n" +
    "      --version            output version information and exit\n\n")
  raise SystemExit

def _version():
   sys.stdout.write(os.path.basename(sys.argv[0]) + " " + VERSION + "\n" +
      "License GPLv3+: GNU GPL version 3 or later.\n"
      "This is free software: you are free to change and redistribute it.\n"
      "There is NO WARRANTY, to the extent permitted by law.\n"
      "Python " + sys.version.split("\n")[0] + "\n")
   raise SystemExit


def _error(_text):
   _path = os.path.basename(sys.argv[0])
   sys.stderr.write(_path + ": " + _text + "\n")

def _abort(_text):
   _path = os.path.basename(sys.argv[0])
   sys.stderr.write(_path + ": " + _text + "\n")
   sys.stderr.write("Try '" + _path + " --help' for more information.\n")
   raise SystemExit

def _reject(_option):
   _abort("invalid value: '" + _option + "'")

def _invalid(_option):
   _abort("invalid option: '" + _option + "'")

def _unrecognized(_option):
   _abort("unrecognized option: '" + _option + "'")

