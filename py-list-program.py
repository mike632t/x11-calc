def _print(_line):
   global _number, _strip, _lines, _blanks
   if len(_line) > 1: _blanks = 0
   if not(_blanks > 1 and _strip):
      if _number:
         _lines += 1
         sys.stdout.write(_expand("%6d  " % _lines))
      sys.stdout.write(_line)
   _blanks += 1

def _flush(_buffer):
   global _line
   for _char in _buffer:
      _line += _char
      _buffer = _buffer[1:]
      if _char in _eoln:
         #sys.stdout.write(_line)
         _print(_line)
         _line = ""

def _expand(_buffer):
   global _format
   global _unicode

   if _unicode:
      for _pattern in _substitutions["unicode"]:
         for _item in _pattern:
            _buffer = _buffer.replace(_item, _pattern[_item])
   else: # Strip out hints for unicode
      for _pattern in _substitutions["text"]:
         for _item in _pattern:
            _buffer = _buffer.replace(_item, _pattern[_item])

   if _format == "markup":
      for _pattern in _substitutions["markup"]:
         for _item in _pattern:
            _buffer = _buffer.replace(_item, _pattern[_item])

   if _format == "html":
      for _pattern in _substitutions["ascii2html"]:
         for _item in _pattern:
            _buffer = _buffer.replace(_item, _pattern[_item])

      for _pattern in _substitutions["ascii2html"]:
         try:
            _buffer = _buffer.decode("utf-8")
            for _pattern in _substitutions["unicode2html"]:
               for _item in _pattern:
                  _buffer = _buffer.replace(_item, _pattern[_item])
            _buffer = _buffer.encode("ascii")
         except:
            pass
   return _buffer

def _get_char(_file):
   _bytes = _file.read(1)
   while _bytes == "\r":
      _bytes = _file.read(1)
   if len(_bytes) > 0:
      try: # Fudge to get script to work with python 2 and 3.
         _char = chr(_bytes[0])
      except:
         _char = _bytes[0]
   else:
      _char = ""
   return _char


